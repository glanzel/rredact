#[derive(Debug, Parser)]
#[command(
    name = "rredact",
    version,
    about = "Fast, reversible redaction of secrets and PII for LLM workflows"
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    Scan(ScanArgs),
    Redact(RedactArgs),
    Restore(RestoreArgs),
    Baseline(BaselineArgs),
    Rules(RulesArgs),
    Variables(VariablesArgs),
    Serve(ServeArgs),
    Init(InitArgs),
}

#[derive(Debug, Args, Clone)]
