/**
 * Structural helpers for the parts of the OpenCode V2 plugin API that the
 * plugin touches. Keeping them structural avoids depending on internal schema
 * packages and keeps the redaction logic unit-testable without a server.
 */

export type TextRedactor = (text: string) => Promise<string>
export type TextRestorer = (text: string) => Promise<string>

const PLACEHOLDER = /\[REDACTED:[A-Z0-9_]+:[A-Za-z0-9]+\]/

export function containsPlaceholder(text: string): boolean {
  return PLACEHOLDER.test(text)
}

interface TextPartLike {
  type?: string
  text?: string
}

interface MentionLike {
  mention?: { start: number; end: number; text: string }
}

export interface PromptLike extends MentionLike {
  text: string
  files?: ReadonlyArray<MentionLike & { description?: string }>
  agents?: ReadonlyArray<MentionLike>
  skills?: ReadonlyArray<MentionLike>
}

export interface ContextLike {
  system?: ReadonlyArray<TextPartLike>
  messages?: ReadonlyArray<unknown>
}

export interface ToolResultLike {
  output?: unknown
  content?: unknown
  metadata?: unknown
}

/**
 * Redact a user prompt and, when the text changed, drop mention offsets that
 * no longer point at the right characters.
 */
export async function redactPrompt(prompt: PromptLike, redact: TextRedactor): Promise<boolean> {
  let changed = false

  const redacted = await redact(prompt.text)
  if (redacted !== prompt.text) {
    prompt.text = redacted
    changed = true
  }

  for (const file of prompt.files ?? []) {
    if (typeof file.description === "string") {
      const value = await redact(file.description)
      if (value !== file.description) file.description = value
    }
  }

  if (changed) clearMentions(prompt)
  return changed
}

export function clearMentions(prompt: PromptLike): void {
  for (const file of prompt.files ?? []) file.mention = undefined
  for (const agent of prompt.agents ?? []) agent.mention = undefined
  for (const skill of prompt.skills ?? []) skill.mention = undefined
}

/**
 * Redact the assembled model request. This is the authoritative egress point:
 * it covers prompts, tool results, attachments and synthetic messages that
 * bypass the prompt hook.
 */
export async function redactContext(context: ContextLike, redact: TextRedactor): Promise<void> {
  for (const part of context.system ?? []) {
    if (typeof part.text === "string") {
      part.text = await redact(part.text)
    }
  }

  for (const message of context.messages ?? []) {
    await redactMessage(message, redact)
  }
}

async function redactMessage(message: unknown, redact: TextRedactor): Promise<void> {
  if (!isRecord(message)) return
  const content = message.content

  if (typeof content === "string") {
    message.content = await redact(content)
    return
  }

  if (!Array.isArray(content)) return
  for (const part of content) {
    await redactPart(part, redact)
  }
}

async function redactPart(part: unknown, redact: TextRedactor): Promise<void> {
  if (!isRecord(part)) return

  switch (part.type) {
    case "text":
    case "reasoning":
    case "compaction": {
      if (typeof part.text === "string") part.text = await redact(part.text)
      return
    }
    case "tool-result": {
      await redactToolResultValue(part.result, redact)
      return
    }
    case "tool-call": {
      // Tool arguments were generated by the model itself, so they are not new
      // egress. Rewriting them could break tool call correlation.
      return
    }
    default: {
      // Future content parts that carry text are still covered.
      if (typeof part.text === "string") part.text = await redact(part.text)
    }
  }
}

async function redactToolResultValue(result: unknown, redact: TextRedactor): Promise<void> {
  if (!isRecord(result)) return

  if (result.type === "content") {
    await redactContent(result.value, redact)
    return
  }

  if ("value" in result) {
    result.value = await redactJsonValue(result.value, redact)
  }
}

/**
 * Redact text content parts (and string content) in place.
 */
export async function redactContent(content: unknown, redact: TextRedactor): Promise<unknown> {
  if (typeof content === "string") return redact(content)
  if (!Array.isArray(content)) return content

  for (const part of content) {
    if (isRecord(part) && part.type === "text" && typeof part.text === "string") {
      part.text = await redact(part.text)
    }
  }
  return content
}

/**
 * Redact a tool result before it is persisted in the transcript.
 */
export async function redactToolResult(
  result: ToolResultLike,
  redact: TextRedactor,
): Promise<ToolResultLike> {
  if (typeof result.output === "string") {
    result.output = await redact(result.output)
  } else if (result.output !== undefined) {
    result.output = await redactJsonValue(result.output, redact)
  }

  if (result.content !== undefined) {
    result.content = await redactContent(result.content, redact)
  }

  return result
}

/**
 * Walk every string in a JSON-like value and redact it. Used for structured
 * tool output and JSON tool results.
 */
export async function redactJsonValue(
  value: unknown,
  redact: TextRedactor,
  seen: WeakSet<object> = new WeakSet(),
  depth = 0,
): Promise<unknown> {
  if (depth > 64) return value
  if (typeof value === "string") {
    if (isBinaryString(value)) return value
    return redact(value)
  }

  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index++) {
      value[index] = await redactJsonValue(value[index], redact, seen, depth + 1)
    }
    return value
  }

  if (!isPlainRecord(value)) return value
  if (seen.has(value)) return value
  seen.add(value)

  for (const key of Object.keys(value)) {
    value[key] = await redactJsonValue(value[key], redact, seen, depth + 1)
  }
  return value
}

/**
 * Restore placeholders in a write/edit tool input before the tool executes, so
 * redacted file contents do not overwrite the real values with placeholders.
 */
export async function restoreToolInput(
  input: unknown,
  restore: TextRestorer,
  seen: WeakSet<object> = new WeakSet(),
  depth = 0,
): Promise<unknown> {
  if (depth > 64) return input
  if (typeof input === "string") {
    if (!containsPlaceholder(input)) return input
    return restore(input)
  }

  if (Array.isArray(input)) {
    for (let index = 0; index < input.length; index++) {
      input[index] = await restoreToolInput(input[index], restore, seen, depth + 1)
    }
    return input
  }

  if (!isPlainRecord(input)) return input
  if (seen.has(input)) return input
  seen.add(input)

  for (const key of Object.keys(input)) {
    input[key] = await restoreToolInput(input[key], restore, seen, depth + 1)
  }
  return input
}

function isRecord(value: unknown): value is Record<string, any> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (!isRecord(value)) return false
  if (value instanceof Date) return false
  if (ArrayBuffer.isView(value)) return false
  if (value instanceof ArrayBuffer) return false
  const prototype = Object.getPrototypeOf(value)
  return prototype === Object.prototype || prototype === null
}

function isBinaryString(value: string): boolean {
  return value.startsWith("data:") && value.includes(";base64,")
}
